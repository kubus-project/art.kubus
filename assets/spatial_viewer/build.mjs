// Builds viewer.bundle.js and THIRD_PARTY_LICENSES.txt. Run with `npm run build`.
//
// The bundle inlines Spark, three.js, fflate and a WebAssembly module built from
// Rust crates. Their MIT (and Zlib) licences require the notice to travel with
// copies, so this build writes it into both shipped artefacts:
//   - viewer.bundle.js starts with a /*! legal comment carrying the Spark,
//     three.js and fflate notices (esbuild keeps `/*!` comments when minifying);
//   - THIRD_PARTY_LICENSES.txt holds all four texts, crate list included. It is a
//     Flutter asset, and the app registers it with LicenseRegistry so it shows on
//     the in-app licence page. The bundle's banner points at it for the crates.
// The texts come from third_party/licenses/, the one place they are maintained.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const here = dirname(fileURLToPath(import.meta.url));
const licences = join(here, "..", "..", "third_party", "licenses");
const text = (name) => readFileSync(join(licences, name), "utf8").replace(/\r\n/g, "\n").trimEnd();

const spark = text("SPARK-MIT.txt");
const three = text("THREE-MIT.txt");
const fflate = text("FFLATE-MIT.txt");
const crates = text("SPARK-WASM-CRATES.txt");

const sections = [
  ["Spark (@sparkjsdev/spark 2.4.0)", spark],
  ["Three.js (three 0.185.1)", three],
  ["fflate (inlined by Spark)", fflate],
  ["Rust crates compiled into Spark's WebAssembly module", crates],
];

const full = [
  "Third-party licences for the spatial viewer (assets/spatial_viewer/viewer.bundle.js)",
  "Generated by assets/spatial_viewer/build.mjs from third_party/licenses/. Do not edit.",
  ...sections.map(([title, body]) => `${"=".repeat(78)}\n${title}\n${"=".repeat(78)}\n\n${body}`),
].join("\n\n") + "\n";
writeFileSync(join(here, "THIRD_PARTY_LICENSES.txt"), full);

// ASCII only in the banner: the bundle is a classic script and must not depend on a charset header.
const ascii = (value) => value.replace(/\u00a9/g, "(c)");
const banner =
  "/*!\n" +
  " * Third-party notices. Spark, three.js and fflate are MIT-licensed; the WebAssembly\n" +
  " * module Spark embeds is built from permissively licensed Rust crates whose notices\n" +
  " * are in THIRD_PARTY_LICENSES.txt (the same directory as this file in the source tree;\n" +
  " * the app's licence page lists it).\n" +
  sections
    .slice(0, 3)
    .map(([title, body]) => ` *\n * ---- ${title} ----\n${ascii(body).split("\n").map((l) => ` * ${l}`.trimEnd()).join("\n")}`)
    .join("\n") +
  "\n */";
if (banner.slice(2, -2).includes("*/")) throw new Error("licence text contains a comment terminator");

await build({
  entryPoints: [join(here, "src", "viewer.js")],
  bundle: true,
  minify: true,
  format: "iife",
  outfile: join(here, "viewer.bundle.js"),
  banner: { js: banner },
  logLevel: "info",
});
